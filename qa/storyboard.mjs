// Generates docs/camera-storyboard.md from the live journey, so the storyboard always
// matches what renders.   node qa/storyboard.mjs
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve } from './shoot.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srv = await serve();
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(`http://127.0.0.1:${srv.address().port}/`);
await page.waitForFunction(() => window.__allBuilt === true, null, { timeout: 60000 });
const data = await page.evaluate(() => {
  const j = __world.world.journey;
  const f = (v) => v.toArray().map((x) => x.toFixed(1)).join(', ');
  return { length: j.length, beats: j.beats.map((b) => {
    const o = b.orbit;
    const pos = new b.shot.pos.constructor().copy(b.shot.pos);
    return {
      id: b.id, island: b.island, s0: b.s0, s1: b.s1, exhibit: b.exhibit, travel: !!b.travel, ride: b.ride || null, title: b.title, finale: b.finale, assemble: b.assemble,
      cam: f(pos), look: f(b.shot.look), fov: b.shot.fov || 36, dist: o.r.toFixed(1), el: (o.el * 180 / Math.PI).toFixed(0),
      from: f(b.path[0]), to: f(b.path[b.path.length - 1]), walk: b.L.toFixed(1), face: b.face ? f(b.face) : '',
    };
  }) };
});
await browser.close(); srv.close();

const kind = (b) => b.title ? 'Establishing (title)' : b.finale ? 'Finale' : b.ride ? 'Ride (cable car)' : b.travel ? 'Bridge crossing' : b.exhibit ? 'Content reveal' : /establish/.test(b.id) ? 'Establishing' : /exit|station/.test(b.id) ? 'Exit' : 'Approach';
const figure = (b) => b.ride ? 'stands in the car, faces travel direction' : b.walk > 0.05 ? `walks ${b.walk} studs, then ${b.face ? 'turns to the exhibit' : 'stands'}` : (b.face ? 'stands, faces the exhibit' : 'stands');
let md = `# Camera storyboard

Generated by \`node qa/storyboard.mjs\` from the running journey (${data.beats.length} beats, ${data.length.toFixed(1)} screens of scroll). Regenerate after changing any island's beats.

## How a beat plays

Scroll position \`s\` is measured in screens (one viewport height of scroll = 1). Each beat owns \`[s0, s1)\`:

1. **Travel (first 60%)**: the camera moves from the previous shot to this beat's shot, interpolated in orbit form around the subject (distance log-lerped, azimuth along the shortest arc, elevation linear) with a smootherstep ease. The figure walks this beat's waypoints at constant speed, posed on twos (12 fps) and advancing in held steps.
2. **Hold (last 40%)**: camera and figure rest. Content (the chapter card, the exhibit line and its Open button) is read here. Scrolling up runs the same mapping backwards.

Cameras for exhibits, bridges and most establishing shots are **auto-framed** (\`World.frame\`): starting from a preferred azimuth, candidates are tested against the brick occupancy grid for a clear line to the subject, a clear line to the figure and the exhibit centre, nothing big in the lens frustum within 12 studs, and the figure not standing between the lens and the exhibit. Positions below are the poses that were chosen.

While touring on desktop the image is shifted 12% of the width (max 200 px) to the right so the subject clears the chapter card; panels shift it left by half the panel width.

## Interaction states and the camera

| State | Camera source | Transition in |
|---|---|---|
| Journey | rail at \`s\` (this table) | 0.9 to 1.0 s blend from the current pose |
| Explore | follow boom behind the figure, azimuth from Q/E or drag, distance 7 to 28, pulls in when bricks block the view | 0.9 s blend, then damped (λ = 7) |
| Panel | the exhibit's shot, image shifted to the free side | 0.9 s blend; a fade cut if the exhibit is more than 30 studs away |
| Map, guide | frozen | none |
| Reduced motion | the current beat's shot, cut at beat boundaries, no figure walking | cut |

## Beats

| # | s | Beat | Kind | Camera position | Target | Lens | Dist / elev | Figure |
|---|---|---|---|---|---|---|---|---|
`;
data.beats.forEach((b, i) => {
  md += `| ${i + 1} | ${b.s0.toFixed(1)}–${b.s1.toFixed(1)} | \`${b.id}\`${b.exhibit ? ` (${b.exhibit})` : ''} | ${kind(b)}${b.assemble ? ', gate assembles' : ''} | ${b.cam} | ${b.look} | ${b.fov}° | ${b.dist} / ${b.el}° | ${figure(b)} |\n`;
});
md += `
## Sequence notes

- **Harbour**: the title holds a wide shot of the whole ring from the south-east, then descends to the dock. During \`harbour:gate\` the gate assembles brick by brick from the pile beside the path, driven by scroll (scrolling back takes it apart). Signpost and noticeboard are framed three-quarter with the figure off-axis. The exit looks west along the plank bridge.
- **Bridges**: side views from outside the ring, so the void and the next island sit behind the span. The figure crosses during the travel phase.
- **Works**: high establishing shot over the chimneys and silo, then five machines in walking order: boiler gauge, inspection gate, reconciliation mill, migration depot, clock tower; then the cable-car station.
- **Works → Lab**: the figure rides the cable car; the car's position is derived from the same scroll value, in held 1/24 steps.
- **Signal Lab**: observatory telescope, context tower, switchboard, analysis bench; exit down the bridge toward the warm Workshop lights.
- **Workshop**: six small exhibits around the shed and yard; the exit glances over the edge toward the Dormant Rock in the fog.
- **Archive**: the figure climbs the timeline stair landing by landing (one brick per year), then comes back down to the parts library and the plinth.
- **Lookout**: lighthouse from below, the lamp-room door, the mailbox, then the finale pulls back to show every island lit, with the end card.
`;
fs.writeFileSync(path.join(ROOT, 'docs/camera-storyboard.md'), md);
console.log(`wrote docs/camera-storyboard.md (${data.beats.length} beats)`);
