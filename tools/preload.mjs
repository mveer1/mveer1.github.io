// Writes <link rel="modulepreload"> hints for the app's static module graph into
// index.html between the PRELOAD markers. Without them the browser discovers the
// graph one import level at a time (main -> app -> core/world/... -> islands), and
// every level costs a network round trip before the hero's 3D world can start.
//
//   node tools/preload.mjs        (or: npm run preload)
//
// Run again after adding or moving a module that the app imports statically.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'index.html');
const START = '<!-- PRELOAD:START (generated by tools/preload.mjs) -->';
const END = '<!-- PRELOAD:END -->';

// Entry points to follow: the app, plus the first island, which app.start() imports
// dynamically before it can reveal the world. The other islands load later, in idle time.
const ENTRIES = ['js/app.js', 'js/world/islands/harbour.js'];

const seen = new Set();
function walk(rel) {
  if (seen.has(rel)) return;
  seen.add(rel);
  const src = fs.readFileSync(path.join(root, rel), 'utf8');
  // static imports/exports only: dynamic import() is deliberately not followed
  for (const m of src.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+'(\.[^']+)'|^\s*import\s+'(\.[^']+)'/gm)) {
    walk(path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1] || m[2])));
  }
}
ENTRIES.forEach(walk);

const links = [...seen].sort().map((f) => `<link rel="modulepreload" href="${f}">`);
const html = fs.readFileSync(file, 'utf8');
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < 0) throw new Error('PRELOAD markers not found in index.html');
fs.writeFileSync(file, html.slice(0, a + START.length) + '\n' + links.join('\n') + '\n' + html.slice(b));
console.log(`modulepreload hints written: ${links.length} modules`);
