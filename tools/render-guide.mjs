// Writes the field guide (all portfolio content as semantic HTML) into
// index.html between the GUIDE markers, so the content is readable with no
// JavaScript and indexable. Run after editing js/content/content.js:
//
//   node tools/render-guide.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { guideHTML } from '../js/content/render.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const file = path.join(here, '..', 'index.html');
const html = fs.readFileSync(file, 'utf8');
const start = '<!-- GUIDE:START (generated by tools/render-guide.mjs from js/content/content.js) -->';
const end = '<!-- GUIDE:END -->';
const a = html.indexOf(start), b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error('GUIDE markers not found in index.html');
const out = html.slice(0, a + start.length) + '\n<div class="guide-body">\n' + guideHTML() + '\n</div>\n' + html.slice(b);
fs.writeFileSync(file, out);
console.log(`field guide written: ${(guideHTML().length / 1024).toFixed(1)} KB`);
